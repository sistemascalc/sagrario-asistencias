// Integration checks run only against disposable data, never the live registry.
const {_electron:electron}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const root=path.resolve(__dirname,'..'),data=path.join(root,'tmp','smoke-'+Date.now());
fs.mkdirSync(data,{recursive:true});
let application;
async function launch(){
  const env={...process.env,SAGRARIO_TEST_DATA:data};delete env.ELECTRON_RUN_AS_NODE;
  application=await electron.launch({args:[root],env,timeout:60000});
  const page=await application.firstWindow();
  await page.getByRole('heading',{name:'Registro de asistencia',exact:true}).waitFor();
  return page;
}
async function main(){
  let page=await launch();
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const source=JSON.parse(fs.readFileSync(path.join(root,'data','seed.json'),'utf8'));
  assert.equal(source.people.length,265);
  await page.screenshot({path:path.join(root,'tmp','app-overview.png')});
  const search=page.getByRole('textbox',{name:'Buscar por número, nombre o padrino'});
  await search.fill('139');
  assert.equal(await page.locator('tbody tr').count(),1);
  await page.getByRole('checkbox',{name:'Asistencia confirmando 139',exact:true}).check();
  await page.getByRole('checkbox',{name:'Asistencia padrino 139',exact:true}).check();
  await page.getByRole('button',{name:'Editar registro 139',exact:true}).click();
  await page.locator('[name=dailyNotes]').fill('Nota de prueba persistente');
  await page.locator('[name=sponsor]').fill('Padrino de prueba corregido');
  await page.getByRole('button',{name:'Guardar cambios',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  assert.ok(await page.getByRole('checkbox',{name:'Asistencia confirmando 139',exact:true}).isChecked());
  await application.close();
  page=await launch();
  await page.getByRole('textbox',{name:'Buscar por número, nombre o padrino'}).fill('139');
  assert.ok(await page.getByRole('checkbox',{name:'Asistencia padrino 139',exact:true}).isChecked());
  assert.equal(await page.getByText('Padrino de prueba corregido',{exact:true}).count(),1);
  await page.getByRole('button',{name:'Editar registro 139',exact:true}).click();
  assert.equal(await page.locator('[name=dailyNotes]').inputValue(),'Nota de prueba persistente');
  await page.screenshot({path:path.join(root,'tmp','app-record.png')});
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.getByRole('button',{name:'Nueva lista',exact:false}).click();
  await page.locator('[name=date]').fill('2026-10-19');
  await page.getByRole('button',{name:'Crear lista',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden'});
  await page.getByRole('textbox',{name:'Buscar por número, nombre o padrino'}).fill('139');
  assert.equal(await page.getByRole('checkbox',{name:'Asistencia confirmando 139',exact:true}).isChecked(),false);
  await page.getByRole('button',{name:'Editar registro 139',exact:true}).click();
  assert.equal(await page.locator('[name=dailyNotes]').inputValue(),'');
  await page.getByRole('button',{name:'Cancelar',exact:true}).click();
  await page.getByRole('button',{name:'Listas y calendario',exact:false}).click();
  await page.getByRole('button',{name:'Crear año completo',exact:false}).click();
  await page.locator('[name=year]').fill('2028');
  await page.getByRole('button',{name:'Crear año completo',exact:true}).click();
  await page.locator('#modal').waitFor({state:'hidden',timeout:60000});
  assert.equal(fs.readdirSync(path.join(data,'lists')).filter(n=>n.endsWith('.json')).length,368);
  await page.locator('#month-select').fill('2028-02');
  await page.locator('#month-select').dispatchEvent('change');
  await page.screenshot({path:path.join(root,'tmp','app-calendar.png')});
  await page.getByRole('button',{name:'29 de febrero de 2028, abrir lista'}).click();
  const pdfPath=path.join(root,'tmp','Asistencia-prueba.pdf');
  await application.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},pdfPath);
  await page.getByRole('button',{name:'Guardar PDF',exact:false}).click();
  await page.getByRole('status').filter({hasText:'Lista guardada:'}).waitFor({timeout:60000});
  assert.ok(fs.statSync(pdfPath).size>10000);
  const csvPath=path.join(root,'tmp','Asistencia-prueba.csv');
  await application.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},csvPath);
  await page.getByRole('button',{name:'Excel / CSV',exact:false}).click();
  await page.getByRole('status').filter({hasText:csvPath}).waitFor();
  assert.equal(fs.readFileSync(csvPath,'utf8').split('\r\n').length,266);
  await page.getByRole('button',{name:'Ajustes y respaldos',exact:false}).click();
  const backupPath=path.join(root,'tmp','Respaldo-prueba.json');
  await application.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},backupPath);
  await page.getByRole('button',{name:'Crear respaldo',exact:false}).click();
  await page.getByRole('status').filter({hasText:'Respaldo guardado:'}).waitFor();
  assert.equal(JSON.parse(fs.readFileSync(backupPath,'utf8')).lists.length,368);
  await page.getByRole('button',{name:'Buscar actualizaciones',exact:true}).click();
  await page.getByText('Las actualizaciones se consultan desde la aplicación instalada.',{exact:true}).waitFor();
  await page.screenshot({path:path.join(root,'tmp','app-settings.png')});
  assert.deepEqual(errors,[]);
  console.log('PASS: 265 imported records; exact number search; both attendance marks; editing and daily notes; restart persistence; new date isolation; 366-day leap year; PDF, CSV, backup and update controls.');
  await application.close();application=null;
}
main().catch(async error=>{console.error(error);if(application)await application.close();process.exitCode=1;});
